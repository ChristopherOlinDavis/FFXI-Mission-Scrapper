#!/bin/bash

# Repository Cleanup Script
# Removes obsolete test files, redundant documentation, and temporary files

echo "================================================================================"
echo "FFXI Mission Scraper - Repository Cleanup"
echo "================================================================================"
echo ""

# Create backup directory for safety
BACKUP_DIR="cleanup-backup-$(date +%Y%m%d-%H%M%S)"
mkdir -p "$BACKUP_DIR"
echo "✅ Created backup directory: $BACKUP_DIR"
echo ""

# Function to safely remove files
safe_remove() {
    local file="$1"
    if [ -f "$file" ]; then
        cp "$file" "$BACKUP_DIR/"
        rm "$file"
        echo "  ✅ Removed: $file"
    fi
}

# Function to safely remove directories
safe_remove_dir() {
    local dir="$1"
    if [ -d "$dir" ]; then
        cp -r "$dir" "$BACKUP_DIR/"
        rm -rf "$dir"
        echo "  ✅ Removed directory: $dir"
    fi
}

