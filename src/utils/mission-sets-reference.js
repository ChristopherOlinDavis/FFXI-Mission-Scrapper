/**
 * Check if a mission title matches any in the reference list
 * (case-insensitive, handles variations like "Jeuno (Mission)" -> "Jeuno")
 */
function normalizeMissionTitle(title) {
  return title
    .replace(/\s*\(Mission\)\s*/i, '')
    .replace(/\s*\(Bastok\)\s*/i, '')
    .replace(/\s*\(San d'Oria\)\s*/i, '')
    .replace(/\s*\(Windurst\)\s*/i, '')
    .replace(/^Aht Urhgan Mission \d+:\s*/i, '')  // Remove "Aht Urhgan Mission #: " prefix
    .trim()
    .toLowerCase();
}

/**
 * Get reference list for a set
 */
function getReferenceList(setId) {
  // Nation missions
  if (setId === 'ffxiclopedia-bastok' || setId === 'bgwiki-bastok') {
    return BASTOK_MISSIONS;
  } else if (setId === 'ffxiclopedia-sandoria') {
    return SANDORIA_MISSIONS;
  } else if (setId === 'ffxiclopedia-windurst') {
    return WINDURST_MISSIONS;
  }
  // Expansion missions
  else if (setId === 'ffxiclopedia-zilart') {
    return ZILART_MISSIONS;
  } else if (setId === 'ffxiclopedia-promathia') {
    return PROMATHIA_MISSIONS;
  } else if (setId === 'ffxiclopedia-aht-urhgan') {
    return AHT_URHGAN_MISSIONS;
  } else if (setId === 'ffxiclopedia-wings-goddess') {
    return WINGS_GODDESS_MISSIONS;
  } else if (setId === 'ffxiclopedia-seekers-adoulin') {
    return SEEKERS_ADOULIN_MISSIONS;
  } else if (setId === 'ffxiclopedia-rhapsodies') {
    return RHAPSODIES_MISSIONS;
  } else if (setId === 'ffxiclopedia-voracious-resurgence') {
    return VORACIOUS_RESURGENCE_MISSIONS;
  }

  return null;
}

/**
 * Check if a mission belongs to a specific set based on title
 */
export function isMissionInSet(missionTitle, setId) {
  const normalizedTitle = normalizeMissionTitle(missionTitle);
  const referenceList = getReferenceList(setId);

  if (!referenceList) {
    // For other sets (quests, assault, campaign, coalition), rely on mission number filtering
    return null;
  }

  return referenceList.some(refTitle =>
    normalizedTitle === normalizeMissionTitle(refTitle)
  );
}

/**
 * Get the order index of a mission in the reference list
 * Returns -1 if not found in reference list
 */
export function getMissionOrderIndex(missionTitle, setId) {
  const normalizedTitle = normalizeMissionTitle(missionTitle);
  const referenceList = getReferenceList(setId);

  if (!referenceList) {
    return -1;
  }

  const index = referenceList.findIndex(refTitle =>
    normalizedTitle === normalizeMissionTitle(refTitle)
  );

  return index;
}

